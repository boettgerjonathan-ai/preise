# Combines data/runs/*.json (one file per day) into data.js for the dashboard.
# Usage: pwsh -File build.ps1            -> rebuild data.js
#        pwsh -File build.ps1 -Publish   -> rebuild, commit and push to GitHub Pages
param([switch]$Publish, [int]$KeepDays = 120)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$runsDir = Join-Path $root 'data/runs'

$files = Get-ChildItem $runsDir -Filter '*.json' | Sort-Object Name | Select-Object -Last $KeepDays
$runs = foreach ($f in $files) {
    $txt = (Get-Content $f.FullName -Raw -Encoding utf8).Trim()
    try { $null = $txt | ConvertFrom-Json } catch { Write-Warning "Skipping invalid JSON: $($f.Name)"; continue }
    $txt
}
if (-not $runs) { throw 'No valid run files found.' }
$js = "// generated by build.ps1 – do not edit`nwindow.PRICE_RUNS = [`n" + ($runs -join ",`n") + "`n];`n"
[IO.File]::WriteAllText((Join-Path $root 'data.js'), $js, [Text.UTF8Encoding]::new($false))
Write-Output "data.js written with $(@($runs).Count) run(s)."

if ($Publish) {
    Push-Location $root
    try {
        git add -A
        git diff --cached --quiet
        if ($LASTEXITCODE -ne 0) {
            git commit -m "Preise $(Get-Date -Format 'yyyy-MM-dd HH:mm')" | Out-Null
        }
        git push -q origin HEAD
        if ($LASTEXITCODE -ne 0) { throw 'git push failed' }
        Write-Output 'Published.'
    } finally { Pop-Location }
}
